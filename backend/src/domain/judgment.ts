/** 심각성 + 성향 → 판결 수위 점수(0~6) */
function verdictScore(severity: Severity, tone: Tone): number {
  const toneOffset = tone === "lenient" ? -1 : tone === "strict" ? 1 : 0;
  return Math.max(0, Math.min(6, severity + toneOffset));
}

